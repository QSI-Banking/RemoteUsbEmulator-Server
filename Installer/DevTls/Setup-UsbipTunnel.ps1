<#
.SYNOPSIS
    DEVELOPMENT ONLY: configures stunnel as a mutual-TLS tunnel for USB/IP.

.DESCRIPTION
    Run by the installers (server MSI and client setup); can also be run by hand from an elevated PowerShell.

    Server role:  stunnel listens on 0.0.0.0:<TunnelPort> (TLS, client certificate required)
                  and forwards to usbipd on 127.0.0.1:<UsbipPort>.
    Client role:  stunnel listens on 127.0.0.1:<UsbipPort> (plain, where the usbip driver connects)
                  and forwards to <ServerAddress>:<TunnelPort> over TLS with the client certificate.

    One server accepts any number of clients: every client presents a certificate issued by the same CA.

    The certificates next to this script are a shared DEVELOPMENT set (see README.md). Anyone with
    these files can connect, so never use them outside a lab.

    If stunnel is not installed, the official win64 installer is downloaded from stunnel.org,
    its SHA-256 is checked against the published .sha256 file, and it is installed silently.

    Log: %ProgramData%\usbip-dev-tls\setup.log

.EXAMPLE
    .\Setup-UsbipTunnel.ps1 -Role Server
    .\Setup-UsbipTunnel.ps1 -Role Client -ServerAddress 192.168.1.10
    .\Setup-UsbipTunnel.ps1 -Role Client -Uninstall
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [ValidateSet('Server', 'Client')]
    [string]$Role,

    [string]$ServerAddress,

    [ValidateRange(1, 65535)]
    [int]$TunnelPort = 3241,

    [ValidateRange(1, 65535)]
    [int]$UsbipPort = 3240,

    [switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 3

$Here = Split-Path -Parent $MyInvocation.MyCommand.Path
$Marker = '; usbip-dev-tls (generated by Setup-UsbipTunnel.ps1, DEVELOPMENT ONLY)'
$ServiceName = 'stunnel'
$FirewallRuleName = 'usbip-dev-tls'
$StunnelUrl = 'https://www.stunnel.org/downloads/stunnel-latest-win64-installer.exe'

$LogDir = Join-Path $env:ProgramData 'usbip-dev-tls'
New-Item -ItemType Directory -Force -Path $LogDir | Out-Null
$Log = Join-Path $LogDir 'setup.log'

function Write-Log([string]$Text) {
    $line = '{0:yyyy-MM-dd HH:mm:ss} [{1}] {2}' -f (Get-Date), $Role, $Text
    Add-Content -Path $Log -Value $line
    Write-Host $line
}

# Returns the executable of a command line such as '"C:\Program Files\stunnel\uninstall.exe" /S', or $null.
function Get-CommandExecutable([string]$Command) {
    if (-not $Command) { return $null }
    $c = $Command.Trim()
    if ($c.StartsWith('"')) {
        $end = $c.IndexOf('"', 1)
        if ($end -gt 1) { return $c.Substring(1, $end - 1) }
        return $null
    }
    $exe = $c.IndexOf('.exe', [StringComparison]::OrdinalIgnoreCase)
    if ($exe -gt 0) { return $c.Substring(0, $exe + 4) }
    return $c
}

function Find-Stunnel {
    $dirs = New-Object System.Collections.Generic.List[string]
    foreach ($key in @(
            'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\stunnel',
            'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\stunnel')) {
        $item = Get-ItemProperty -Path $key -ErrorAction SilentlyContinue
        if (-not $item) { continue }
        if ($item.PSObject.Properties['InstallLocation'] -and $item.InstallLocation) {
            $dirs.Add($item.InstallLocation.Trim().Trim('"'))
        }
        if ($item.PSObject.Properties['UninstallString'] -and $item.UninstallString) {
            $exe = Get-CommandExecutable $item.UninstallString
            if ($exe) { $dirs.Add([System.IO.Path]::GetDirectoryName($exe)) }
        }
    }
    $dirs.Add((Join-Path $env:ProgramFiles 'stunnel'))
    if (${env:ProgramFiles(x86)}) { $dirs.Add((Join-Path ${env:ProgramFiles(x86)} 'stunnel')) }

    foreach ($dir in $dirs) {
        try {
            if (-not $dir) { continue }
            $candidate = [System.IO.Path]::Combine($dir, 'bin', 'stunnel.exe')
            if (Test-Path -LiteralPath $candidate) { return (Resolve-Path -LiteralPath $candidate).Path }
        }
        catch {
            Write-Log "ignoring unusable stunnel location '$dir': $($_.Exception.Message)"
        }
    }
    return $null
}

function Get-Text([string]$Url) {
    $content = (Invoke-WebRequest -Uri $Url -UseBasicParsing).Content
    if ($content -is [byte[]]) { $content = [System.Text.Encoding]::ASCII.GetString($content) }
    return [string]$content
}

function Install-Stunnel {
    Write-Log "stunnel not found; downloading $StunnelUrl"
    [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

    $dir = Join-Path $env:TEMP ('usbip-stunnel-' + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $dir | Out-Null
    try {
        $exe = Join-Path $dir 'stunnel-win64-installer.exe'
        $ProgressPreference = 'SilentlyContinue'
        Invoke-WebRequest -Uri $StunnelUrl -OutFile $exe -UseBasicParsing

        $expected = ((Get-Text "$StunnelUrl.sha256").Trim() -split '\s+')[0].TrimStart('*')
        $actual = (Get-FileHash -LiteralPath $exe -Algorithm SHA256).Hash
        if ($expected -notmatch '^[0-9A-Fa-f]{64}$' -or $actual -ne $expected) {
            throw "stunnel installer checksum mismatch (expected '$expected', got '$actual')."
        }
        Write-Log "checksum OK ($actual)"

        $signature = Get-AuthenticodeSignature -LiteralPath $exe
        $signer = if ($signature.SignerCertificate) { $signature.SignerCertificate.Subject } else { 'none' }
        Write-Log "Authenticode: $($signature.Status), signer: $signer"

        $p = Start-Process -FilePath $exe -ArgumentList '/S' -Wait -PassThru
        if ($p.ExitCode -ne 0) { throw "stunnel installer exited with code $($p.ExitCode)." }
    }
    finally {
        Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
    }

    $stunnel = Find-Stunnel
    if (-not $stunnel) { throw 'stunnel was installed but stunnel.exe could not be found.' }
    Write-Log "installed $stunnel"
    return $stunnel
}

function Stop-StunnelService {
    $svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
    if ($svc -and $svc.Status -ne 'Stopped') {
        Write-Log 'stopping stunnel service'
        Stop-Service -Name $ServiceName -Force
        $svc.WaitForStatus('Stopped', [TimeSpan]::FromSeconds(30))
    }
    return $svc
}

function Protect-KeyFile([string]$Path) {
    # SYSTEM and Administrators only
    & icacls.exe $Path /inheritance:r /grant:r '*S-1-5-18:F' '*S-1-5-32-544:F' | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "icacls failed on $Path" }
}

function Wait-Listening([int]$Port) {
    for ($i = 0; $i -lt 20; $i++) {
        if (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue) { return $true }
        Start-Sleep -Milliseconds 500
    }
    return $false
}

try {
    Write-Log "start: Role=$Role ServerAddress=$ServerAddress TunnelPort=$TunnelPort UsbipPort=$UsbipPort Uninstall=$Uninstall"

    $stunnel = Find-Stunnel

    # ---------------------------------------------------------------- uninstall
    if ($Uninstall) {
        Remove-NetFirewallRule -Name $FirewallRuleName -ErrorAction SilentlyContinue
        if (-not $stunnel) {
            Write-Log 'stunnel not found; nothing to undo'
            exit 0
        }
        $configDir = Join-Path (Split-Path -Parent (Split-Path -Parent $stunnel)) 'config'
        $conf = Join-Path $configDir 'stunnel.conf'
        if ((Test-Path -LiteralPath $conf) -and ((Get-Content -LiteralPath $conf -TotalCount 1) -eq $Marker)) {
            if (Stop-StunnelService) {
                Write-Log 'removing stunnel service'
                Start-Process -FilePath $stunnel -ArgumentList '-uninstall', '-quiet' -Wait | Out-Null
            }
            $backup = "$conf.usbip-backup"
            if (Test-Path -LiteralPath $backup) {
                Move-Item -LiteralPath $backup -Destination $conf -Force
                Write-Log 'restored the original stunnel.conf'
            }
            else {
                Remove-Item -LiteralPath $conf -Force
            }
        }
        Remove-Item -LiteralPath (Join-Path $configDir 'usbip') -Recurse -Force -ErrorAction SilentlyContinue
        Write-Log 'uninstall done (the stunnel program itself is left installed)'
        exit 0
    }

    # ---------------------------------------------------------------- install
    if ($Role -eq 'Client') {
        if (-not $ServerAddress) { throw 'ServerAddress is required for the client role.' }
        if ($ServerAddress -notmatch '^[A-Za-z0-9.\-]+$') {
            throw "ServerAddress '$ServerAddress' must be an IPv4 address or a host name."
        }
    }

    if (-not $stunnel) { $stunnel = Install-Stunnel }
    Write-Log "using $stunnel"

    $configDir = Join-Path (Split-Path -Parent (Split-Path -Parent $stunnel)) 'config'
    $certDir = Join-Path $configDir 'usbip'
    $conf = Join-Path $configDir 'stunnel.conf'
    New-Item -ItemType Directory -Force -Path $certDir | Out-Null

    $null = Stop-StunnelService

    # Keep the user's own stunnel.conf once; ours starts with the marker line.
    if ((Test-Path -LiteralPath $conf) -and ((Get-Content -LiteralPath $conf -TotalCount 1) -ne $Marker)) {
        Copy-Item -LiteralPath $conf -Destination "$conf.usbip-backup" -Force
        Write-Log 'backed up the existing stunnel.conf'
    }

    $leaf = if ($Role -eq 'Server') { 'server' } else { 'client' }
    foreach ($name in 'ca.crt', "$leaf.crt", "$leaf.key") {
        $src = Join-Path $Here $name
        if (-not (Test-Path -LiteralPath $src)) { throw "missing $src" }
        Copy-Item -LiteralPath $src -Destination (Join-Path $certDir $name) -Force
    }
    Protect-KeyFile (Join-Path $certDir "$leaf.key")

    $ca = Join-Path $certDir 'ca.crt'
    $crt = Join-Path $certDir "$leaf.crt"
    $key = Join-Path $certDir "$leaf.key"
    $stunnelLog = Join-Path $LogDir 'stunnel.log'

    $common = @(
        $Marker
        "output = $stunnelLog"
        'debug = info'
        ''
    )
    if ($Role -eq 'Server') {
        $service = @(
            '[usbip-server]'
            "accept = 0.0.0.0:$TunnelPort"
            "connect = 127.0.0.1:$UsbipPort"
            "cert = $crt"
            "key = $key"
            "CAfile = $ca"
            'verifyChain = yes'
            'requireCert = yes'
            'sslVersionMin = TLSv1.2'
            # every attach is a full handshake with the client certificate
            'sessionCacheSize = 1'
            'sessionCacheTimeout = 1'
            'socket = l:TCP_NODELAY=1'
            'socket = r:TCP_NODELAY=1'
            'socket = l:SO_KEEPALIVE=1'
        )
        $listenPort = $TunnelPort
    }
    else {
        $service = @(
            '[usbip-client]'
            'client = yes'
            "accept = 127.0.0.1:$UsbipPort"
            "connect = ${ServerAddress}:$TunnelPort"
            "cert = $crt"
            "key = $key"
            "CAfile = $ca"
            'verifyChain = yes'
            # the server certificate is checked by name, so clients may use any server IP address
            'checkHost = usbip-dev-server'
            'sslVersionMin = TLSv1.2'
            'socket = l:TCP_NODELAY=1'
            'socket = r:TCP_NODELAY=1'
            'socket = r:SO_KEEPALIVE=1'
        )
        $listenPort = $UsbipPort
    }
    Set-Content -LiteralPath $conf -Value ($common + $service) -Encoding ASCII
    Write-Log "wrote $conf"

    if (-not (Get-Service -Name $ServiceName -ErrorAction SilentlyContinue)) {
        Write-Log 'installing stunnel service'
        Start-Process -FilePath $stunnel -ArgumentList '-install', '-quiet', "`"$conf`"" -Wait | Out-Null
    }
    Set-Service -Name $ServiceName -StartupType Automatic
    Start-Service -Name $ServiceName
    Write-Log 'stunnel service started'

    if ($Role -eq 'Server') {
        Remove-NetFirewallRule -Name $FirewallRuleName -ErrorAction SilentlyContinue
        # Port-only rule: a rule restricted to stunnel.exe did not match the stunnel service's traffic.
        New-NetFirewallRule -Name $FirewallRuleName -DisplayName 'USB/IP development TLS tunnel (stunnel)' `
            -Direction Inbound -Protocol TCP -LocalPort $TunnelPort -Action Allow -Profile Any | Out-Null
        Write-Log "firewall: inbound TCP $TunnelPort allowed for stunnel"
    }

    if (-not (Wait-Listening $listenPort)) {
        throw "stunnel is not listening on port $listenPort; see $stunnelLog"
    }
    Write-Log "OK: stunnel listening on port $listenPort"
    exit 0
}
catch {
    Write-Log "ERROR: $($_.Exception.Message)"
    exit 1
}
